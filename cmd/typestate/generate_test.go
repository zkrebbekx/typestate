package main

import (
	"testing"

	. "github.com/smartystreets/goconvey/convey"
)

const sampleSrc = `package widget

import "time"

type Server struct {
	Addr    string        ` + "`typestate:\"required\"`" + `
	Handler string        ` + "`typestate:\"required\"`" + `
	Timeout time.Duration
	maxConn int
}
`

func TestParse(t *testing.T) {
	Convey("Given a source file with an annotated struct", t, func() {
		Convey("When the struct is parsed", func() {
			spec, err := parse("server.go", []byte(sampleSrc), "Server")

			Convey("Then it succeeds and reads the package and type names", func() {
				So(err, ShouldBeNil)
				So(spec.Package, ShouldEqual, "widget")
				So(spec.TypeName, ShouldEqual, "Server")
			})

			Convey("Then only the two tagged fields are required", func() {
				So(spec.requiredNames(), ShouldResemble, []string{"Addr", "Handler"})
			})

			Convey("Then the unexported optional field is dropped", func() {
				for _, f := range spec.Fields {
					So(f.Name, ShouldNotEqual, "maxConn")
				}
			})

			Convey("Then the import for an optional field's type is recorded", func() {
				So(spec.Imports["time"], ShouldEqual, "time")
			})
		})

		Convey("When a missing type is requested", func() {
			_, err := parse("server.go", []byte(sampleSrc), "Nope")

			Convey("Then it errors", func() {
				So(err, ShouldNotBeNil)
				So(err.Error(), ShouldContainSubstring, "not found")
			})
		})
	})

	Convey("Given a struct with an unexported required field", t, func() {
		src := `package p
type Bad struct {
	secret string ` + "`typestate:\"required\"`" + `
}`
		Convey("When parsed", func() {
			_, err := parse("p.go", []byte(src), "Bad")

			Convey("Then it errors clearly", func() {
				So(err, ShouldNotBeNil)
				So(err.Error(), ShouldContainSubstring, "unexported but marked required")
			})
		})
	})
}

func TestGenerate(t *testing.T) {
	Convey("Given a parsed builder spec", t, func() {
		spec, err := parse("server.go", []byte(sampleSrc), "Server")
		So(err, ShouldBeNil)

		Convey("When the builder is generated", func() {
			out, err := generate(spec)
			So(err, ShouldBeNil)
			code := string(out)

			Convey("Then the output is valid, gofmt'd Go with the DO NOT EDIT header", func() {
				So(code, ShouldStartWith, "// Code generated by")
				So(code, ShouldContainSubstring, "package widget")
			})

			Convey("Then required fields become type parameters", func() {
				So(code, ShouldContainSubstring, "type ServerBuilder[Addr, Handler ts.Flag] struct")
			})

			Convey("Then each WithX flips only its own slot", func() {
				So(code, ShouldContainSubstring, "WithAddr(v string) ServerBuilder[ts.Set, Handler]")
				So(code, ShouldContainSubstring, "WithHandler(v string) ServerBuilder[Addr, ts.Set]")
			})

			Convey("Then optional setters leave the typestate unchanged", func() {
				So(code, ShouldContainSubstring, "WithTimeout(v time.Duration) ServerBuilder[Addr, Handler]")
			})

			Convey("Then the terminal guard is pinned to all-Set", func() {
				So(code, ShouldContainSubstring, "func BuildServer(b ServerBuilder[ts.Set, ts.Set]) Server")
			})

			Convey("Then the field-type import is carried through", func() {
				So(code, ShouldContainSubstring, `"time"`)
			})
		})
	})
}

func TestStructTagParsing(t *testing.T) {
	Convey("Given struct tags in various shapes", t, func() {
		cases := []struct {
			tag, key, want string
		}{
			{`typestate:"required"`, "typestate", "required"},
			{`json:"x" typestate:"required"`, "typestate", "required"},
			{`json:"x"`, "typestate", ""},
			{``, "typestate", ""},
		}
		Convey("When each is read", func() {
			Convey("Then the typestate value is extracted correctly", func() {
				for _, c := range cases {
					So(reflectStructTag(c.tag).get(c.key), ShouldEqual, c.want)
				}
			})
		})
	})
}

func TestZeroRequiredFields(t *testing.T) {
	Convey("Given a struct with no required fields", t, func() {
		src := `package p
type Opt struct {
	A string
	B int
}`
		Convey("When generated", func() {
			spec, err := parse("p.go", []byte(src), "Opt")
			So(err, ShouldBeNil)
			out, err := generate(spec)
			So(err, ShouldBeNil)
			code := string(out)

			Convey("Then the builder is non-generic and always buildable", func() {
				So(code, ShouldContainSubstring, "type OptBuilder struct")
				So(code, ShouldContainSubstring, "func BuildOpt(b OptBuilder) Opt")
				So(code, ShouldNotContainSubstring, "ts.Flag")
			})
		})
	})
}
